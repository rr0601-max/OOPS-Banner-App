public class SamAverage {
    public static void main(String[] args) {
        // marks as variables
        int math = 94;
        int physics = 95;
        int chemistry = 96;

        double average = (math + physics + chemistry) / 3.0; // type conversion
        System.out.println("Sam’s average mark in PCM is " + average);
    }
}